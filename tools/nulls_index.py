"""Build experiments/NULLS.md: one searchable index of known negative results, by task.

    python tools/nulls_index.py            # rewrites experiments/NULLS.md

Sources (read only):
- third_party/manwithacat-vqcc-negative-results/ledger.csv (manwithacat, Apache-2.0): one row per idea tried by
  that team or credited to other entrants, with outcome, key numbers, reason and "reopen if";
- the "Known nulls" tables of Analysis/research/{invsqrt,dqi,chemistry,general}.md (our S1.9 research).

The index keeps the columns needed to decide whether an idea is closed: ID, mechanism, family, outcome, key
numbers, why it failed, when to reopen, later status, source. Cells are truncated for readability; the full
rows stay in the sources. Cost: O(rows).
"""
from __future__ import annotations

import csv
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LEDGER = os.path.join(REPO, "third_party", "manwithacat-vqcc-negative-results", "ledger.csv")
RESEARCH = {"invsqrt": "invsqrt", "dqi": "dqi", "chemistry": "chemistry", "all": "general"}
OUT = os.path.join(REPO, "experiments", "NULLS.md")


def cut(s: str, n: int) -> str:
    s = " ".join((s or "").split()).replace("|", "/")
    return s if len(s) <= n else s[: n - 1] + "…"


def research_nulls(name: str) -> list[list[str]]:
    """Rows of the first table under a 'Known nulls' heading of Analysis/research/<name>.md."""
    path = os.path.join(REPO, "Analysis", "research", f"{name}.md")
    rows, inside, in_table = [], False, False
    for line in open(path, encoding="utf-8"):
        if line.startswith("## "):
            inside = "known nulls" in line.lower()
            in_table = False
            continue
        if not inside:
            continue
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if set("".join(cells)) <= set("-: "):
                in_table = True
                continue
            if in_table:
                rows.append(cells)
        else:
            in_table = in_table and line.strip() != ""
    return rows


def main() -> None:
    with open(LEDGER, encoding="utf-8", newline="") as f:
        ledger = list(csv.DictReader(f))
    out = ["# Known negative results (index)", "",
           "Generated by `tools/nulls_index.py`; do not edit by hand. Check this index before starting an idea: a",
           "null is closed only in its design family (see each row's family and *reopen if*). Full rows:",
           "`third_party/manwithacat-vqcc-negative-results/ledger.csv` (manwithacat, Apache-2.0; their NOTICE applies)",
           "and the *Known nulls* sections of `Analysis/research/*.md`. Our own attempts are in `experiments/LEDGER.md`.",
           "", f"Counts: {len(ledger)} community rows; outcomes "
           + ", ".join(f"{k} {sum(1 for r in ledger if r['outcome'] == k)}" for k in ("kill", "null", "partial", "observation", "open idea")) + ".", ""]
    titles = {"invsqrt": "invsqrt", "dqi": "dqi", "chemistry": "Chemistry (dfthcsos)", "all": "Cross-cutting and tooling"}
    for task, title in titles.items():
        rows = [r for r in ledger if r["task"] == task]
        out += [f"## {title}", "", f"### Community ledger ({len(rows)} rows)", "",
                "| ID | Mechanism | Family / target | Outcome | Key numbers | Why it failed | Reopen if | Later | Source |",
                "|---|---|---|---|---|---|---|---|---|"]
        for r in rows:
            out.append("| " + " | ".join([r["id"], cut(r["mechanism"], 90), cut(r["family_target"], 50), r["outcome"],
                                           cut(r["key_numbers"], 90), cut(r["why_it_failed"], 110), cut(r["reopen_if"], 70),
                                           cut(r["later_status"], 14), cut(r["source"], 20)]) + " |")
        rn = research_nulls(RESEARCH[task])
        out += ["", f"### From our research (`Analysis/research/{RESEARCH[task]}.md`, {len(rn)} rows)", "",
                "| Ref | What was tried | Result | Source |", "|---|---|---|---|"]
        for cells in rn:
            cells = (cells + ["", "", "", ""])[:4] if len(cells) >= 4 else [""] + (cells + ["", "", ""])[:3]
            out.append("| " + " | ".join(cut(c, 110) for c in cells) + " |")
        out.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {OUT}: {len(ledger)} community rows + research nulls")


if __name__ == "__main__":
    main()
